export function getDepartmentById(id: WorkshopDepartment | string): DepartmentInfo | undefined {
  return WORKSHOP_DEPARTMENTS.find((d) => d.id === id);
}

export function getDepartmentByName(name: string): DepartmentInfo | undefined {
  const norm = (name || '').toLowerCase().trim();
  return WORKSHOP_DEPARTMENTS.find(
    (d) =>
      d.name.toLowerCase().includes(norm) ||
      norm.includes(d.name.toLowerCase()) ||
      d.code.toLowerCase() === norm
  );
}

export function getDepartmentsForProcess(processType: DaleProcessType): DepartmentInfo[] {
  return WORKSHOP_DEPARTMENTS.filter((d) =>
    d.linkedProcesses.includes(processType)
  );
}
